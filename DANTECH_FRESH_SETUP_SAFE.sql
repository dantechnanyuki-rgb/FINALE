-- Automatically create a safe staff profile after a new Auth user.
-- New users are ALWAYS staff in Branch 1. The first admin is assigned explicitly
-- from Supabase SQL Editor using ADMIN_SETUP.sql. This prevents a normal signup
-- from promoting itself to admin.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,full_name,role,branch)
 values(
   new.id,
   coalesce(new.raw_user_meta_data->>'full_name',''),
   'staff',
   case
     when new.raw_user_meta_data->>'branch' in ('Branch 1','Branch 2')
       then new.raw_user_meta_data->>'branch'
     else 'Branch 1'
   end
 )
 on conflict (id) do nothing;
 return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

-- Purchase transaction: increases stock and records purchase atomically.
create or replace function public.record_purchase(p_product_id uuid,p_supplier text,p_quantity integer,p_unit_cost numeric,p_branch text)
returns void language plpgsql security definer set search_path=public as $$
declare p products;
begin
 if my_role()<>'admin' then raise exception 'Admin only'; end if;
 select * into p from products where id=p_product_id for update;
 if p.id is null or p.branch<>p_branch then raise exception 'Product not found'; end if;
 update products set qty=qty+p_quantity where id=p.id;
 insert into purchases(supplier,product_id,product_name,quantity,unit_cost,total,branch,created_by)
 values(p_supplier,p.id,p.name,p_quantity,p_unit_cost,p_quantity*p_unit_cost,p_branch,auth.uid());
end; $$;

create or replace function public.transfer_stock(p_product_id uuid,p_quantity integer,p_to_branch text)
returns void language plpgsql security definer set search_path=public as $$
declare p products; target products;
begin
 if my_role()<>'admin' then raise exception 'Admin only'; end if;
 select * into p from products where id=p_product_id for update;
 if p.id is null or p.branch=p_to_branch or p.qty<p_quantity then raise exception 'Invalid transfer'; end if;
 select * into target from products where sku=p.sku and branch=p_to_branch limit 1 for update;
 if target.id is null then
   insert into products(name,sku,category,cost_price,selling_price,qty,low_stock_threshold,branch)
   values(p.name,p.sku,p.category,p.cost_price,p.selling_price,0,p.low_stock_threshold,p_to_branch) returning * into target;
 end if;
 update products set qty=qty-p_quantity where id=p.id;
 update products set qty=qty+p_quantity where id=target.id;
 insert into transfers(product_name,product_id,from_branch,to_branch,quantity,created_by)
 values(p.name,p.id,p.branch,p_to_branch,p_quantity,auth.uid());
end; $$;


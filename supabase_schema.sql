create extension if not exists pgcrypto;

create type public.app_role as enum ('admin','staff');

create table public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '',
 role public.app_role not null default 'staff',
 branch text not null default 'Branch 1' check(branch in ('Branch 1','Branch 2')),
 created_at timestamptz not null default now()
);

create table public.products(
 id uuid primary key default gen_random_uuid(), name text not null, sku text, category text default 'Stationery',
 cost_price numeric(12,2) not null default 0, selling_price numeric(12,2) not null default 0,
 qty integer not null default 0 check(qty>=0), low_stock_threshold integer not null default 5,
 branch text not null check(branch in ('Branch 1','Branch 2')), created_at timestamptz not null default now()
);

create table public.services(
 id uuid primary key default gen_random_uuid(), name text not null, price numeric(12,2) not null default 0,
 branch text not null check(branch in ('Branch 1','Branch 2')), created_by uuid references auth.users(id), created_at timestamptz not null default now()
);

create table public.sales(
 id uuid primary key default gen_random_uuid(), user_id uuid references auth.users(id), branch text not null check(branch in ('Branch 1','Branch 2')),
 item_name text not null, product_id uuid references products(id), service_id uuid references services(id),
 quantity integer not null default 1 check(quantity>0), unit_price numeric(12,2) not null, subtotal numeric(12,2) not null,
 discount numeric(12,2) not null default 0, final_total numeric(12,2) not null, cost_total numeric(12,2) not null default 0,
 profit numeric(12,2) not null default 0, payment_method text not null check(payment_method in ('Cash','M-Pesa','Card','Other')),
 mpesa_reference text, sale_date date not null default current_date, created_at timestamptz not null default now()
);

create table public.expenses(
 id uuid primary key default gen_random_uuid(), description text not null, amount numeric(12,2) not null check(amount>=0),
 branch text not null check(branch in ('Branch 1','Branch 2')), expense_date date not null default current_date,
 created_by uuid references auth.users(id), created_at timestamptz not null default now()
);

create table public.purchases(
 id uuid primary key default gen_random_uuid(), supplier text not null, product_id uuid references products(id),
 product_name text not null, quantity integer not null, unit_cost numeric(12,2) not null, total numeric(12,2) not null,
 branch text not null check(branch in ('Branch 1','Branch 2')), purchase_date date not null default current_date,
 created_by uuid references auth.users(id), created_at timestamptz not null default now()
);

create table public.transfers(
 id uuid primary key default gen_random_uuid(), product_name text not null, product_id uuid references products(id),
 from_branch text not null, to_branch text not null, quantity integer not null, transfer_date date not null default current_date,
 created_by uuid references auth.users(id), created_at timestamptz not null default now()
);

create table public.activity(
 id bigint generated by default as identity primary key, user_id uuid references auth.users(id), branch text,
 action text not null, created_at timestamptz not null default now()
);

create or replace function public.my_role() returns public.app_role
language sql stable security definer set search_path=public as $$
 select role from public.profiles where id=auth.uid()
$$;

create or replace function public.my_branch() returns text
language sql stable security definer set search_path=public as $$
 select branch from public.profiles where id=auth.uid()
$$;

